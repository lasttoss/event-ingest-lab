#!/usr/bin/env bash
# Runs each arm from an empty table and writes the results to docs/measurements.md.
#
# Two things are held still across arms: the events (same seed, same count, same POST size) and the
# machine. One thing changes: how the ingest path turns those events into INSERT statements. That is
# the variable the question is actually about.
set -euo pipefail
cd "$(dirname "$0")/.."

EVENTS="${EVENTS:-20000}"
SCALE_EVENTS="${SCALE_EVENTS:-200000}"
OUT=docs/measurements.md
# One run, one document. Every block below appends, so the file has to be emptied once here:
# without it a second `make measure` added a whole second copy of the report to the first one.
: > "${OUT}"
API_PORT=8099

# The health check is not "something answers" - it is "the API I started is the one answering, and it
# is running the mode I asked for". Anything less and an arm can silently measure another arm.
wait_healthy() {
  local want="$1"
  for _ in $(seq 1 60); do
    local body
    body="$(curl -sf "http://127.0.0.1:${API_PORT}/healthz" 2>/dev/null || true)"
    case "${body}" in
      *"mode=${want}"*) echo "  api up: ${body}"; return 0 ;;
      "") ;;
      *) echo "  refusing to measure: ${API_PORT} answered as ${body}" >&2; exit 1 ;;
    esac
    sleep 1
  done
  echo "the ingest api never came up in mode ${want} on ${API_PORT}" >&2
  return 1
}

stop_api() {
  [ -n "${api_pid:-}" ] || return 0
  kill "${api_pid}" 2>/dev/null || true
  for _ in $(seq 1 20); do kill -0 "${api_pid}" 2>/dev/null || break; sleep 0.5; done
  kill -9 "${api_pid}" 2>/dev/null || true
  wait "${api_pid}" 2>/dev/null || true
  api_pid=""
}
trap 'stop_api' EXIT

run_arm() {
  local mode="$1" label="$2" events="$3"
  echo "== arm: ${mode} (${events} events)"
  rm -f data/wal/*.ndjson
  go build -o /tmp/lab-api ./cmd/api
  /tmp/lab-api -mode "${mode}" -clickhouse http://127.0.0.1:8123 -table lab.events \
      -wal-dir data/wal >>/tmp/lab-api.log 2>&1 &
  api_pid=$!
  wait_healthy "${mode}"
  LAB_OUT="${OUT}" go run ./cmd/lab -mode "${mode}" -label "${label}" -events "${events}" -settle 60s
  stop_api
}

{
  echo "# Measurements"
  echo
  echo "Generated by \`make measure\`. Each arm starts from an empty table and pushes the same synthetic"
  echo "events (same seed, same count, same POST size - 200 events per POST, which is what a game client"
  echo "sends after being offline). The only variable is how the ingest path turns those events into"
  echo "INSERT statements."
  echo
  echo "- Machine: $(nproc) cores, $(free -g | awk '/^Mem:/{print $2}') GiB RAM, $(uname -srm)"
  echo "- ClickHouse: $(curl -s http://127.0.0.1:8123/ --data-binary 'SELECT version()' 2>/dev/null | head -1)"
  echo "- Vector: $(docker compose logs vector 2>/dev/null | grep -oE 'version="[0-9.]+"' | tail -1 | tr -d 'version=\"')"
  echo
  echo "## The question"
  echo
  echo "> ClickHouse cannot take a lot of requests per second - is that true, and does it mean the"
  echo "> pipeline needs a queue in front of it?"
  echo
  echo "## The answer, in one line"
  echo
  echo "ClickHouse cannot take many INSERT *statements* per second, and that limit is a property of the"
  echo "writer, not of the database: the same events that fail as 20,000 single-row inserts land as a"
  echo "handful of large inserts with the same server, the same table and the same hardware."
  echo
} >> "${OUT}"

run_arm per-event "Arm A - one INSERT per event (the mistake, kept so it can be measured)" "${EVENTS}"
run_arm batched   "Arm B - WAL -> Vector -> batched inserts (5000 rows per insert, async_insert)" "${EVENTS}"
run_arm batched   "Arm B at scale - the same batched path, ${SCALE_EVENTS} events" "${SCALE_EVENTS}"

echo
echo "docs/measurements.md written"
